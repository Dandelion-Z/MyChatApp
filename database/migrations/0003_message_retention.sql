-- -----------------------------------------------------------------------------
-- 消息保留策略支持
-- 说明：服务端只保留最近一段时间的消息（默认 30 天），
--       过期清理按 created_at 从旧到新扫描，需要单独的 created_at 索引。
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_messages_created_at
    ON messages (created_at);
